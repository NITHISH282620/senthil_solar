/**
 * Same nested shape as `en`, every leaf widened to `string`. Deriving
 * `Dictionary` from `typeof en` directly (with `en` as `const`) would make
 * every English leaf a string LITERAL type, so `ta.ts` would only type-check
 * if its strings were byte-identical to the English ones — the opposite of
 * what this is for. Widening keeps the compile-time guarantee that matters
 * (Tamil has every key English has, nothing missing, nothing extra) without
 * demanding the values match.
 */
type Widen<T> = { [K in keyof T]: T[K] extends string ? string : Widen<T[K]> };
export type Dictionary = Widen<typeof en>;

export default en;
